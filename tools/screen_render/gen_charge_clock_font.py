"""Rasterize tall condensed digits for the charging clock into a 1-bit header.

The charging clock fills the whole screen with HH:MM, so the font must be
narrow: Calibri runs out of width long before height on 128x64 and 240x135.
DIN Condensed Bold is tall and narrow.

Each digit is centred in a cell of the same width, so the time does not
jump sideways when a 1 changes to an 8. Faces are fitted to the screens the
firmware drives (physical pixels):

  128x64  OLED            (Heltec V3/V4, T-Beam, T-LoRa, Station G2)
  160x80  ST7735          (Heltec Tracker, T096)
  240x135 ST7789          (Heltec T114) - also used, centred, on larger TFTs

A corner band of text takes 9 logical rows (of 64) at the top and at the
bottom, so the digits get the height in between.

Usage: python3 gen_charge_clock_font.py [path/to/font.ttf]
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FONT = sys.argv[1] if len(sys.argv) > 1 else "/System/Library/Fonts/Supplemental/DIN Condensed Bold.ttf"
OUT = os.path.join(ROOT, "src", "helpers", "ui", "ChargeClockFont.h")
DIGITS = "0123456789"

# (name, screen width, screen height)
SCREENS = [
    ("CHARGE_DIGIT_S", 128, 64),
    ("CHARGE_DIGIT_M", 160, 80),
    ("CHARGE_DIGIT_L", 240, 135),
]


def band(h):
    return (9 * h + 63) // 64


def render(size, ch):
    """Ink of one character at 4x, box-filtered down. Returns (image, bbox) in 1x pixels."""
    scale = 4
    big = ImageFont.truetype(FONT, size * scale)
    canvas = Image.new("L", (size * scale * 3, size * scale * 3), 255)
    ImageDraw.Draw(canvas).text((size * scale, size * scale), ch, font=big, fill=0)
    small = canvas.resize((canvas.width // scale, canvas.height // scale), Image.Resampling.BOX)
    bw = small.point(lambda p: 0 if p < 140 else 255)
    inv = bw.point(lambda p: 255 - p)
    return bw, inv.getbbox()


def face_metrics(size):
    """Digit cell width, digit ink top/bottom, colon width, gaps."""
    boxes = {c: render(size, c)[1] for c in DIGITS}
    cell = max(b[2] - b[0] for b in boxes.values())
    top = min(b[1] for b in boxes.values())
    bot = max(b[3] for b in boxes.values())
    colon = render(size, ":")[1]
    gap = max(2, size // 14)
    width = 4 * cell + 3 * gap + (colon[2] - colon[0]) + 2 * gap
    return cell, top, bot, colon, gap, width


def fit(max_w, max_h):
    lo, hi, best = 8, 400, 8
    while lo <= hi:
        mid = (lo + hi) // 2
        cell, top, bot, colon, gap, width = face_metrics(mid)
        if width <= max_w and bot - top <= max_h:
            best = mid
            lo = mid + 1
        else:
            hi = mid - 1
    return best


def pack(img, x0, y0, w, h):
    pix = img.load()
    out = bytearray()
    for y in range(y0, y0 + h):
        for col in range((w + 7) // 8):
            byte = 0
            for b in range(8):
                x = x0 + col * 8 + b
                if col * 8 + b < w and 0 <= x < img.width and 0 <= y < img.height and pix[x, y] == 0:
                    byte |= 0x80 >> b
            out.append(byte)
    return out


def emit(name, size):
    cell, top, bot, colon, gap, width = face_metrics(size)
    glyphs = []
    blob = bytearray()
    for ch in DIGITS:
        img, box = render(size, ch)
        w = box[2] - box[0]
        x0 = box[0] - (cell - w) // 2      # centre the ink in the cell
        bits = pack(img, x0, top, cell, bot - top)
        glyphs.append((ch, cell, bot - top, cell + gap, 0, len(blob)))
        blob.extend(bits)
    img, box = render(size, ":")
    cw = box[2] - box[0]
    bits = pack(img, box[0], box[1], cw, box[3] - box[1])
    glyphs.append((":", cw, box[3] - box[1], cw + gap, box[1] - top, len(blob)))
    blob.extend(bits)

    lines = ["// %s: font size %d, digits %dx%d, HH:MM %d px wide" % (name, size, cell, bot - top, width - gap)]
    lines.append("static const uint8_t %s_BITS[] PROGMEM = {" % name)
    for i in range(0, len(blob), 16):
        lines.append("  " + ", ".join("0x%02x" % b for b in blob[i:i + 16]) + ",")
    lines.append("};")
    lines.append("static const ClockGlyph %s_GLYPHS[] PROGMEM = {" % name)
    for ch, w, h, adv, t, off in glyphs:
        lines.append("  { '%s', %d, %d, %d, %d, %d }," % (ch, w, h, adv, t, off))
    lines.append("};")
    lines.append("static const ClockFace %s = { %d, %s_GLYPHS, %s_BITS };" % (name, len(glyphs), name, name))
    return "\n".join(lines), len(blob)


def main():
    parts = []
    total = 0
    for name, w, h in SCREENS:
        size = fit(w - 2, h - 2 * band(h))
        text, n = emit(name, size)
        parts.append(text)
        total += n
        print(name, "size", size, "bytes", n)
    header = """#pragma once

// Tall condensed digits for the charging clock (DIN Condensed Bold, 1-bit).
// Generated by tools/screen_render/gen_charge_clock_font.py - do not edit.
// Digits share one cell width, so HH:MM never shifts sideways.

#include "ClockFont.h"

%s

// Largest first: the clock picks the first face that fits the screen.
static const ClockFace* const CHARGE_DIGIT_FACES[] = { &CHARGE_DIGIT_L, &CHARGE_DIGIT_M, &CHARGE_DIGIT_S };
""" % "\n\n".join(parts)
    with open(OUT, "w", newline="\n") as f:
        f.write(header)
    print("total bitmap bytes", total, "->", OUT)


if __name__ == "__main__":
    main()
