#!/usr/bin/env python3
# docs/track.html -> examples/companion_radio/TrackPage.h (the page the WiFi
# builds serve). Run after editing the page.
import io, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
html = io.open(os.path.join(root, 'docs', 'track.html'), encoding='utf-8').read()
assert ')TRKPAGE"' not in html
out = ('#pragma once\n// generated by tools/gen_track_page.py from docs/track.html - do not edit\n'
       '#include <Arduino.h>\nstatic const char TRACK_PAGE[] PROGMEM = R"TRKPAGE(' + html + ')TRKPAGE";\n')
io.open(os.path.join(root, 'examples', 'companion_radio', 'TrackPage.h'), 'w', encoding='utf-8').write(out)
print('TrackPage.h:', len(html.encode('utf-8')), 'bytes')
