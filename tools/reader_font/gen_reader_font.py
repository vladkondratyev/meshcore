#!/usr/bin/env python3
"""Generates src/helpers/reader/ReaderFont.h: the e-book reader faces.

Books are stored on the device in Windows-1251, one byte per character, so the
font is indexed by that byte: glyph i draws byte 0x20 + i (224 glyphs). It
covers ASCII, Russian, Ukrainian and Belarusian letters and the book
punctuation of CP1251 (guillemets, dashes, ellipsis, typographic quotes, No.).

The faces are rendered from PT Sans (ParaType, SIL Open Font License 1.1)
without anti-aliasing, at several pixel sizes. Each glyph keeps the full
line height in rows, plus its own ink width and left bearing.

Usage:
  python tools/reader_font/gen_reader_font.py [--font PTSans.ttc] [--preview out.png]
"""

import argparse
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "src", "helpers", "reader", "ReaderFont.h")
FONT_CANDIDATES = [
    "/System/Library/Fonts/Supplemental/PTSans.ttc",
    "/usr/share/fonts/truetype/paratype/PTS55F.ttf",
    "/usr/share/fonts/opentype/paratype/PTSans-Regular.otf",
    r"C:\Windows\Fonts\PTSans-Regular.ttf",
    "PT_Sans-Web-Regular.ttf",
]

# name, pixel size passed to FreeType, extra line gap
FACES = [
    ("S", 12, 1),
    ("M", 14, 1),
    ("L", 17, 1),
    ("XL", 21, 1),
]

FIRST = 0x20


def cp1251_char(b):
    if b == 0xA0:
        return " "        # no-break space draws as a space
    if b == 0xAD:
        return "-"        # soft hyphen draws as a hyphen at a line break
    try:
        return bytes([b]).decode("cp1251")
    except UnicodeDecodeError:
        return " "        # 0x98 is unassigned


def find_font(path):
    if path:
        return path
    for p in FONT_CANDIDATES:
        if os.path.isfile(p):
            return p
    raise SystemExit("PT Sans not found, pass --font")


def render_glyph(font, ch, ascent, descent):
    size = font.size * 3 + 8
    img = Image.new("1", (size * 2, size * 2), 0)
    dr = ImageDraw.Draw(img)
    dr.fontmode = "1"
    ox, oy = size // 2, size
    dr.text((ox, oy), ch, font=font, fill=1, anchor="ls")
    px = img.load()
    ink = []
    for y in range(img.height):
        for x in range(img.width):
            if px[x, y]:
                gy = y - oy + ascent          # row from the top of the line
                if 0 <= gy < ascent + descent:
                    ink.append((x - ox, gy))
    adv = int(round(font.getlength(ch)))
    return adv, ink


def build_face(path, index, px):
    font = ImageFont.truetype(path, px, index=index)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs = []
    for b in range(FIRST, 0x100):
        adv, ink = render_glyph(font, cp1251_char(b), ascent, descent)
        if ink:
            x0 = min(x for x, _ in ink)
            x1 = max(x for x, _ in ink)
            w = x1 - x0 + 1
        else:
            x0, w = 0, 0
        rowb = (w + 7) // 8
        bits = bytearray(rowb * height)
        for x, y in ink:
            cx = x - x0
            bits[y * rowb + (cx >> 3)] |= 0x80 >> (cx & 7)
        glyphs.append((adv, x0, w, bytes(bits)))
    return ascent, height, glyphs


def emit(faces):
    out = []
    out.append("#pragma once\n")
    out.append("// Generated by tools/reader_font/gen_reader_font.py - do not edit.")
    out.append("// Bitmaps rendered from PT Sans, (c) ParaType Inc., SIL Open Font License 1.1.")
    out.append("// Glyph i draws Windows-1251 byte 0x20 + i. Rows span the whole line height.\n")
    out.append("#include <stdint.h>")
    out.append("#include \"ReaderTypes.h\"\n")
    total = 0
    for name, (ascent, height, line, glyphs) in faces.items():
        p = "RF_" + name
        offs, blob = [], bytearray()
        for adv, x0, w, bits in glyphs:
            offs.append(len(blob))
            blob += bits
        total += len(blob) + len(glyphs) * 5
        out.append("static const uint8_t %s_ADV[224] = {%s};" % (p, ",".join(str(g[0]) for g in glyphs)))
        out.append("static const int8_t %s_XO[224] = {%s};" % (p, ",".join(str(g[1]) for g in glyphs)))
        out.append("static const uint8_t %s_W[224] = {%s};" % (p, ",".join(str(g[2]) for g in glyphs)))
        out.append("static const uint16_t %s_OFF[224] = {%s};" % (p, ",".join(str(o) for o in offs)))
        lines = []
        for i in range(0, len(blob), 24):
            lines.append("  " + ",".join("0x%02x" % v for v in blob[i:i + 24]))
        out.append("static const uint8_t %s_BITS[%d] = {\n%s\n};" % (p, max(1, len(blob)), ",\n".join(lines) or "  0"))
        out.append("static const ReaderFace %s = { \"%s\", %d, %d, %d, %s_ADV, %s_XO, %s_W, %s_OFF, %s_BITS };\n"
                   % (p, name, height, ascent, line, p, p, p, p, p))
    out.append("static const ReaderFace* const READER_FACES[] = { %s };" % ", ".join("&RF_" + n for n in faces))
    out.append("static const uint8_t READER_FACE_COUNT = %d;" % len(faces))
    out.append("// font data: %d bytes" % total)
    return "\n".join(out) + "\n", total


def preview(faces, path):
    sample = ("«Глава первая». Всё смешалось в доме Облонских — жена узнала, "
              "что муж был в связи с бывшею в их доме француженкою-гувернанткой… "
              "Ґанок, їжак, Ўладзімір, № 5, 1234567890 (quick brown fox).")
    data = sample.encode("cp1251")
    W, H, Z = 250, 122, 3
    sheet = Image.new("L", ((W + 4) * Z, (H + 4) * len(faces) * Z), 128)
    for fi, (name, (ascent, height, line, glyphs)) in enumerate(faces.items()):
        img = Image.new("L", (W, H), 255)
        px = img.load()
        x, y = 3, 2
        for b in data:
            adv, x0, w, bits = glyphs[b - FIRST]
            if x + adv > W - 3:
                x, y = 3, y + line
            if y + height > H:
                break
            rowb = (w + 7) // 8
            for r in range(height):
                for c in range(w):
                    if bits[r * rowb + (c >> 3)] & (0x80 >> (c & 7)):
                        X, Y = x + x0 + c, y + r
                        if 0 <= X < W and 0 <= Y < H:
                            px[X, Y] = 0
            x += adv
        sheet.paste(img.resize((W * Z, H * Z), Image.NEAREST), (2 * Z, (fi * (H + 4) + 2) * Z))
    sheet.save(path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font")
    ap.add_argument("--index", type=int, default=0, help="face index inside a .ttc")
    ap.add_argument("--preview")
    args = ap.parse_args()
    path = find_font(args.font)
    faces = {}
    for name, px, gap in FACES:
        ascent, height, glyphs = build_face(path, args.index, px)
        faces[name] = (ascent, height, height + gap, glyphs)
        print("%-2s px=%d height=%d ascent=%d line=%d" % (name, px, height, ascent, height + gap))
    text, total = emit(faces)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (%d bytes of font data)" % (OUT, total))
    if args.preview:
        preview(faces, args.preview)
        print("preview", args.preview)


if __name__ == "__main__":
    main()
