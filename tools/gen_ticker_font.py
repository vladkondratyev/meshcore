def columns(rows):
    w = len(rows[0])
    return [sum(1 << y for y in range(7) if rows[y][x] == '#') for x in range(w)]


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "src", "helpers", "ui", "TickerFont.h")
    items = sorted(G.items(), key=lambda kv: ord(kv[0]))
    lines = [
        "#pragma once",
        "// Generated by tools/gen_ticker_font.py -- do not edit by hand.",
        "// 5x7 dot-matrix capitals for the running-line message view.",
        "// cols[i]: bit 0 = top row. w = glyph width in dots (gap not included).",
        "#include <stdint.h>",
        "",
        "struct TickerGlyph { uint16_t cp; uint8_t w; uint8_t cols[5]; };",
        "",
        "static const TickerGlyph TICKER_GLYPHS[] = {",
    ]
    for ch, rows in items:
        c = columns(rows) + [0] * (5 - len(rows[0]))
        esc = {"'": "quote", '"': "dquote", "\\": "backslash"}.get(ch, ch)
        lines.append("  { 0x%04X, %d, { %s } },  // %s" % (
            ord(ch), len(rows[0]), ", ".join("0x%02X" % v for v in c), esc))
    lines += [
        "};",
        "static const int TICKER_GLYPH_COUNT = sizeof(TICKER_GLYPHS) / sizeof(TICKER_GLYPHS[0]);",
        "",
    ]
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote", out, len(items), "glyphs")

    if len(sys.argv) > 2 and sys.argv[1] == "--json":
        with open(sys.argv[2], "w", encoding="utf-8") as f:
            json.dump({ch: columns(rows) for ch, rows in items}, f, ensure_ascii=False)
        print("wrote", sys.argv[2])


if __name__ == "__main__":
    main()
